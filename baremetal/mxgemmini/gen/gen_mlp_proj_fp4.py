#!/usr/bin/env python3
"""Data + golden for src/mlp_proj_fp4.c: the FP4 MLP's two projection shapes, small enough for RTL simulation, on the
real activations of llama_mlp_e2e_fp4 (xn, h: FP4 codes two rows per byte + E8M0 scales, from the golden):

  gate: G[:, :NG] = xn @ Wg[:, :NG]      K 2048     (weights 2048 x NG)
  down: Y[:, :ND] = h  @ Wd[:, :ND]      K 5632     (weights 5632 x ND; h re-read once per 256-column chunk)

Weight slices are contiguous ([K][N/2] packed, scales [K/32][N]); the expected hashes are the golden's G / Y slices.

    ../../../.venv/bin/python3 gen_mlp_proj_fp4.py [--ng 512 --nd 512]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

import golden_llama_layer_e2e as G
from gen_llama_mlp_fp4 import pk_cols, pk_rows, DATA


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ng", type=int, default=512)
    ap.add_argument("--nd", type=int, default=512)
    a = ap.parse_args()
    get, d = G.load()
    M, D, F = d["M"], d["D"], d["F"]
    eps = float(next(l for l in (DATA / "llama_layer_e2e.h").read_text().splitlines() if "E2E_EPS" in l).split()[2].rstrip("f"))
    H, w = get("H_PRE", np.uint16, (M, D)), get("W_POST_LN", np.uint16, (D,))
    Wf = G.fp4_model_weights()
    W = {n: G.mxfp4_weights(Wf[n], 0) for n in ("G", "U", "D")}
    rq = lambda x: G.spad_requant_fp4(x, 0)
    xc, xs = G.rms(H, w, G.vpu_bf(1.0 / D), G.vpu_bf(np.float32(eps)), rq)
    Gb = G.mesh(xc, xs, *W["G"], decode=G.fp4_decode)
    Ub = G.mesh(xc, xs, *W["U"], decode=G.fp4_decode)
    hc, hs = rq(G.v_mul(G.v_mul(Ub, Gb), G.v_rcp(G.v_add(G.v_exp(G.v_mul(Gb, np.uint16(0xBF80))), np.uint16(0x3F80)))))
    wg, wgs = W["G"][0][:, :a.ng], W["G"][1][:, :a.ng]
    wd, wds = W["D"][0][:, :a.nd], W["D"][1][:, :a.nd]
    Gs = np.ascontiguousarray(Gb[:, :a.ng])
    Ys = G.mesh(hc, hs, wd, wds, decode=G.fp4_decode)
    parts = [("XN4", pk_rows(xc)), ("XN_S", np.ascontiguousarray(xs.T)), ("H4", pk_rows(hc)), ("H_S", np.ascontiguousarray(hs.T)),
             ("WG4", pk_cols(wg)), ("WG_S", np.ascontiguousarray(wgs)), ("WD4", pk_cols(wd)), ("WD_S", np.ascontiguousarray(wds))]
    buf, offs = bytearray(), []
    for n, x in parts:
        buf += bytes((-len(buf)) % 64)
        offs.append((n, len(buf), x.shape))
        buf += np.ascontiguousarray(x).tobytes()
    (DATA / "mlp_proj_fp4.bin").write_bytes(bytes(buf))
    (DATA / "mlp_proj_fp4.h").write_text(
        "// GENERATED by gen/gen_mlp_proj_fp4.py -- do not edit. FP4 projection shapes of llama_mlp_e2e_fp4 for "
        "src/mlp_proj_fp4.c.\n#ifndef INCLUDE_MLP_PROJ_FP4_H\n#define INCLUDE_MLP_PROJ_FP4_H\n#include <stdint.h>\n"
        f"#define MP_M {M}\n#define MP_D {D}\n#define MP_F {F}\n#define MP_NG {a.ng}\n#define MP_ND {a.nd}\n"
        "extern const uint8_t _binary_mlp_proj_fp4_bin_start[];\n"
        "#define MP_AT(off, type) ((const type *) (_binary_mlp_proj_fp4_bin_start + (off)))\n"
        + "".join(f"#define MP_OFF_{n:<5s} {o}u   // {s}\n" for n, o, s in offs)
        + f"#define MP_HASH_G 0x{G.fnv(Gs):016x}ULL\n#define MP_HASH_Y 0x{G.fnv(Ys):016x}ULL\n#endif\n")
    print(f"  wrote mlp_proj_fp4.bin ({len(buf) / 1e6:.2f} MB), .h: G hash {G.fnv(Gs):016x}, Y hash {G.fnv(Ys):016x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
