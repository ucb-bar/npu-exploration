#!/usr/bin/env python3
"""Data + goldens for src/llama_mlp_e2e.c: TinyLlama layer 5's MLP block on the device, on the layer's input h_pre:
xn = MX(rmsnorm(h_pre) * w_post); G, U = xn @ Wg, Wu; h = MX(silu(G) * U); y = h @ Wd; h_out = h_pre + y.

  llama_mlp_e2e      E4M3 (weights from data/llama_layer_e2e.bin)
  llama_mlp_e2e_fp4  FP4 x FP4 projections, FP4 SPAD_REQUANT of xn and h. data/llama_mlp_fp4.bin: H_PRE, W_POST_LN
                     and the MXFP4 (pmax 0) weights packed [K][N/2] (low nibble = even column), scales [K/32][N]

Expected hashes (data/llama_mlp_e2e{,_fp4}_expect.h) from the bit-exact golden (golden_llama_layer_e2e ports): xn, g, u,
h, ymlp, hout in the kernel's buffers (FP4 codes as two rows per byte: [M/2][N]).

    ../../../.venv/bin/python3 gen_llama_mlp_fp4.py
"""
from __future__ import annotations

import time
from pathlib import Path

import numpy as np

import golden_llama_layer_e2e as G

DATA = Path(__file__).resolve().parent.parent / "data"
pk_rows = lambda c: (c[0::2] | (c[1::2] << 4)).astype(np.uint8)          # [M][N] -> [M/2][N]
pk_cols = lambda c: (c[:, 0::2] | (c[:, 1::2] << 4)).astype(np.uint8)    # [K][N] -> [K][N/2]


def mlp(H, w, W, M, D, eps, fp4):
    rq = (lambda x: G.spad_requant_fp4(x, 0)) if fp4 else G.spad_requant
    dec = G.fp4_decode if fp4 else G.e4m3_decode
    xc, xs = G.rms(H, w, G.vpu_bf(1.0 / D), G.vpu_bf(np.float32(eps)), rq)
    Gb = G.mesh(xc, xs, *W["G"], decode=dec)
    Ub = G.mesh(xc, xs, *W["U"], decode=dec)
    U = G.v_mul(Ub, Gb)
    Gs = G.v_rcp(G.v_add(G.v_exp(G.v_mul(Gb, np.uint16(0xBF80))), np.uint16(0x3F80)))
    hc, hs = rq(G.v_mul(U, Gs))
    Ym = G.mesh(hc, hs, *W["D"], decode=dec)
    Hout = G.v_add(H, Ym)
    p = pk_rows if fp4 else (lambda c: c)
    return [("xn", p(xc)), ("g", Gb), ("u", Ub), ("h", p(hc)), ("ymlp", Ym), ("hout", Hout)], Hout


def main() -> int:
    get, d = G.load()
    M, D, F = d["M"], d["D"], d["F"]
    eps = float(next(l for l in (DATA / "llama_layer_e2e.h").read_text().splitlines() if "E2E_EPS" in l).split()[2].rstrip("f"))
    H, w = get("H_PRE", np.uint16, (M, D)), get("W_POST_LN", np.uint16, (D,))
    ref_upd = None
    t0 = time.time()
    W8 = {n: (get(f"W{n}_CODES", np.uint8, (k, nn)), get(f"W{n}_SCALES", np.uint8, (k // 32, nn)))
          for n, k, nn in (("G", D, F), ("U", D, F), ("D", F, D))}
    Wf = G.fp4_model_weights()
    W4 = {n: G.mxfp4_weights(Wf[n], 0) for n in ("G", "U", "D")}
    print(f"  weights ({time.time() - t0:.0f}s)", flush=True)
    for tag, W, fp4 in (("", W8, False), ("_fp4", W4, True)):
        st, Hout = mlp(H, w, W, M, D, eps, fp4)
        hs = [G.fnv(a) for _, a in st]
        # accuracy of the MLP update vs fp64 (unquantized fp32 weights) from the same BF16 input
        Hf = G.bf2f(H).astype(np.float64)
        wf = G.bf2f(w).astype(np.float64)
        xn = Hf / np.sqrt((Hf * Hf).mean(1, keepdims=True) + eps) * wf
        g, u = xn @ Wf["G"].astype(np.float64), xn @ Wf["U"].astype(np.float64)
        y = (g / (1 + np.exp(-g)) * u) @ Wf["D"].astype(np.float64)
        upd = G.bf2f(Hout).astype(np.float64) - Hf
        rel = np.linalg.norm(upd - y) / np.linalg.norm(y)
        print(f"  llama_mlp_e2e{tag}: " + " ".join(f"{n} {h:016x}" for (n, _), h in zip(st, hs)) +
              f"; MLP update rel_fro vs fp64 {rel:.4f} ({time.time() - t0:.0f}s)", flush=True)
        (DATA / f"llama_mlp_e2e{tag}_expect.h").write_text(
            f"// golden (gen/gen_llama_mlp_fp4.py, bit-exact rtl_exact mesh + VPU + SPAD_REQUANT ports): "
            f"xn, g, u, h, ymlp, hout\nstatic const uint64_t MLP_EXPECT[6] = {{"
            + ", ".join(f"0x{h:016x}ULL" for h in hs) + "};\n")
    # FP4 blob
    parts = [("H_PRE", H), ("W_POST_LN", w)]
    for n in ("G", "U", "D"):
        parts += [(f"W{n}4_CODES", pk_cols(W4[n][0])), (f"W{n}_SCALES", W4[n][1])]
    buf, offs = bytearray(), []
    for n, a in parts:
        buf += bytes((-len(buf)) % 64)
        offs.append((n, len(buf), a.shape))
        buf += np.ascontiguousarray(a).tobytes()
    (DATA / "llama_mlp_fp4.bin").write_bytes(bytes(buf))
    (DATA / "llama_mlp_fp4.h").write_text(
        "// GENERATED by gen/gen_llama_mlp_fp4.py -- do not edit. FP4 MLP data for src/llama_mlp_e2e.c (MLP_FP4).\n"
        "#ifndef INCLUDE_LLAMA_MLP_FP4_H\n#define INCLUDE_LLAMA_MLP_FP4_H\n#include <stdint.h>\n"
        "extern const uint8_t _binary_llama_mlp_fp4_bin_start[];\n"
        "#define MLP4_AT(off, type) ((const type *) (_binary_llama_mlp_fp4_bin_start + (off)))\n"
        + "".join(f"#define MLP4_OFF_{n:<12s} {o}u   // {s}\n" for n, o, s in offs) + "#endif\n")
    print(f"  wrote llama_mlp_fp4.bin ({len(buf) / 1e6:.1f} MB), .h, expect headers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
