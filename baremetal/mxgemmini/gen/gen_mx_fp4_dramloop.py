#!/usr/bin/env python3
"""Data for src/mx_fp4_dramloop.c: one FP4 x FP4 native DRAM-loop matmul (mxn_matmul_fp4), C = A @ B in BF16.

A [M][K] and B [K][N] are MXFP4 (golden_llama_layer_e2e.mxfp4_weights, pmax 0) of random data with per-block range
spread; A packed [M/2][K] (byte (r, k) = row 2r low nibble | row 2r+1 high), B packed [K][N/2] (low = even column),
scales [K/32][M] / [K/32][N]. The expected C is the golden's rtl_exact mesh on the decoded operands.

    ../../../.venv/bin/python3 gen_mx_fp4_dramloop.py [--m 64 --k 1024 --n 1024]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

import golden_llama_layer_e2e as G

DATA = Path(__file__).resolve().parent.parent / "data"


def carr(name, a, ctype):
    flat = ", ".join(str(int(x)) for x in np.asarray(a).reshape(-1))
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const {ctype} {name}{dims} __attribute__((aligned(64))) = {{{flat}}};\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--m", type=int, default=64)
    ap.add_argument("--k", type=int, default=1024)
    ap.add_argument("--n", type=int, default=1024)
    a = ap.parse_args()
    M, K, N = a.m, a.k, a.n
    rng = np.random.default_rng(4)
    Af = rng.standard_normal((M, K)) * np.exp2(rng.integers(-4, 5, (M, K // 32))).repeat(32, 1)
    Bf = rng.standard_normal((K, N)) * np.exp2(rng.integers(-4, 5, (K // 32, N))).repeat(32, 0)
    at_c, a_sc = G.mxfp4_weights(Af.T.astype(np.float32), 0)     # [K][M], [K/32][M]
    b_c, b_sc = G.mxfp4_weights(Bf.astype(np.float32), 0)        # [K][N], [K/32][N]
    a_c = at_c.T
    C = G.mesh(a_c, a_sc.T, b_c, b_sc, decode=G.fp4_decode)
    a_pk = (a_c[0::2] | (a_c[1::2] << 4)).astype(np.uint8)        # [M/2][K]
    b_pk = (b_c[:, 0::2] | (b_c[:, 1::2] << 4)).astype(np.uint8)  # [K][N/2]
    h = DATA / "mx_fp4_dramloop.h"
    h.write_text(f"// GENERATED by gen/gen_mx_fp4_dramloop.py -- do not edit.\n"
                 f"#ifndef MX_FP4_DRAMLOOP_H\n#define MX_FP4_DRAMLOOP_H\n#include <stdint.h>\n"
                 f"#define FP4T_M {M}\n#define FP4T_K {K}\n#define FP4T_N {N}\n"
                 + carr("FP4T_A", a_pk, "uint8_t") + carr("FP4T_ASC", a_sc, "uint8_t")
                 + carr("FP4T_B", b_pk, "uint8_t") + carr("FP4T_BSC", b_sc, "uint8_t")
                 + carr("FP4T_C", C, "uint16_t") + "#endif\n")
    print(f"wrote {h}: M={M} K={K} N={N}, C nonzero {np.count_nonzero(C)}/{C.size}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
