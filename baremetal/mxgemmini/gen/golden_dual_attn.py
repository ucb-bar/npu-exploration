#!/usr/bin/env python3
"""Bit-exact goldens for src/dual_attn_llama.c: every pass of a gen_attn_vpu.py --layer header (GQA passes of one KV
group) through src/attn_flash.c's pipelined order (golden_attn_flash.flash), at one Gemmini's DIM: the rtl_exact mesh
under that DIM's config and the VPU RSUM lane tree over DIM/2 lanes (golden_llama_layer_mx). 1/sqrt(d) is folded into
Q's E8M0 scales as the kernel does (d = 64: -3). Writes data/<tag>_d<DIM>_expect.h: EXP_DUAL_HASH_O[NPASS].

    ../../../.venv/bin/python3 golden_dual_attn.py ../data/attn_vpu_dual_kv0.h --dim 8 --bk 128
"""
from __future__ import annotations

import argparse
import os
import re
from multiprocessing import get_context
from pathlib import Path

for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ.setdefault(_v, "1")
import numpy as np  # noqa: E402

import golden_attn_flash as GF  # noqa: E402
import golden_llama_layer_e2e as GL  # noqa: E402
import golden_llama_layer_mx as GM  # noqa: E402

_A = {}


def _pass(p):
    a = _A
    qc, qs = a["LQ"][p], a["LQS"][p].astype(np.int64) - a["fold"]          # qs [D/32][SQ] -> folded
    kt, kts, vc, vs = a["KT"], a["KTS"], a["V"], a["VS"]
    off, m, L, O, alpha = 0, None, None, None, None
    for j, b in enumerate(a["BL"]):
        S = GM.mesh(GL.e4m3_decode(qc), qs.T, GL.e4m3_decode(kt[:, off:off + b]), kts[:, off:off + b], pool=False)
        mt = GL.v_rmax(S)
        if j == 0:
            m = mt
        else:
            mn = GL.v_max(m, mt); alpha = GL.v_exp(GL.v_sub(m, mn)); m = mn
        P = GL.v_exp(GL.v_sub(S, m[:, None]))
        lt = GM.v_rsum(P)
        L = lt if j == 0 else GL.v_add(GL.v_mul(L, alpha), lt)
        pc, ps = GL.spad_requant(P)
        Oj = GM.mesh(GL.e4m3_decode(pc), ps, GL.e4m3_decode(vc[off:off + b]), vs[off // 32:(off + b) // 32], pool=False)
        O = Oj if j == 0 else GL.v_add(GL.v_mul(O, alpha[:, None]), Oj)
        off += b
    O = GL.v_mul(O, GL.v_rcp(L)[:, None])
    return p, GM.fnv(O)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("header", type=Path)
    ap.add_argument("--dim", type=int, required=True, choices=(8, 16, 32))
    ap.add_argument("--bk", type=int, default=128)
    a = ap.parse_args()
    GM._DIM, GM._VL = a.dim, a.dim // 2
    t = a.header.read_text()
    d = {k: int(v) for k, v in re.findall(r"#define ATTN_(SQ|SK|D|NPASS|NKV|SCALE_IN_Q)\s+(\d+)", t)}
    SQ, SK, D, NP = d["SQ"], d["SK"], d["D"], d["NPASS"]
    assert d["NKV"] == 1, "one KV group per header"
    _A.update(
        LQ=GF.c_array(t, "LQ_IN", np.uint8).reshape(NP, SQ, D),
        LQS=GF.c_array(t, "LQ_SCALES", np.uint8).reshape(NP, D // 32, SQ),
        KT=GF.c_array(t, "LKT_IN", np.uint8).reshape(D, SK), KTS=GF.c_array(t, "LKT_SCALES", np.uint8).reshape(D // 32, SK),
        V=GF.c_array(t, "LV_IN", np.uint8).reshape(SK, D), VS=GF.c_array(t, "LV_SCALES", np.uint8).reshape(SK // 32, D),
        fold=0 if d.get("SCALE_IN_Q") else {16: 2, 64: 3, 256: 4}[D], BL=GF.blocks(SK, a.bk))
    hashes = [0] * NP
    with get_context("fork").Pool(NP) as pool:
        for p, h in pool.imap_unordered(_pass, range(NP)):
            hashes[p] = h
            print(f"  pass {p}: O hash {h:016x}", flush=True)
    tag = a.header.stem.replace("attn_vpu_", "attn_")
    out = a.header.parent / f"{tag}_d{a.dim}_expect.h"
    body = ", ".join(f"0x{h:016x}ULL" for h in hashes)
    out.write_text(f"// GENERATED by gen/golden_dual_attn.py {a.header.name} --dim {a.dim} --bk {a.bk}\n"
                   f"static const uint64_t EXP_DUAL_HASH_O_D{a.dim}[{NP}] = {{ {body} }};\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
