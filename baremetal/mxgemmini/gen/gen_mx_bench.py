"""Random fp8 E4M3 + E8M0 data blob for the single-matmul utilization benchmark (src/mx_bench_matmul.c).

Layout (all 64 B aligned): A [MMAX][K] codes, B [K][N] codes, A_sc [K/32][MMAX], B_sc [K/32][N], and
B_BLK = the same B pre-blocked for the M=32 tiling (NC 512, Kt 128): block (c, t) = B[t*Kt:+Kt][c*NC:+NC]
stored contiguously (pitch NC), blocks in loop order c-major.
Codes keep the exponent MSB clear (|x| < 2, never NaN); scales are 2^-3 .. 2^3 around 1.
Usage: python3 gen/gen_mx_bench.py   (writes data/mx_bench.bin + data/mx_bench.h)"""
import random
MMAX, K, N = 128, 4096, 1024
rng = random.Random(20260929)
def codes(n): return bytes((b & 0x80) | (b & 0x3f) for b in rng.randbytes(n))
def scales(n): return bytes(124 + rng.randrange(7) for _ in range(n))
A_ = codes(MMAX * K); B_ = codes(K * N)
BLK_NC, BLK_KT = 512, 128
blk = bytearray()
for c in range(N // BLK_NC):
    for t in range(K // BLK_KT):
        for r in range(BLK_KT):
            row = (t * BLK_KT + r) * N + c * BLK_NC
            blk += B_[row:row + BLK_NC]
parts = [("A", A_), ("B", B_), ("A_SC", scales(K // 32 * MMAX)), ("B_SC", scales(K // 32 * N)), ("B_BLK", bytes(blk))]
off, blob, hdr = 0, bytearray(), []
for name, data in parts:
    hdr.append(f"#define MXB_OFF_{name} {off}u")
    blob += data + bytes((-len(data)) % 64)
    off = len(blob)
open("data/mx_bench.bin", "wb").write(blob)
open("data/mx_bench.h", "w").write(f"""// Generated by gen/gen_mx_bench.py -- do not edit.
#pragma once
#include <stdint.h>
#define MXB_MMAX {MMAX}
#define MXB_K    {K}
#define MXB_N    {N}
#define MXB_BLK_NC {BLK_NC}
#define MXB_BLK_KT {BLK_KT}
{chr(10).join(hdr)}
extern const uint8_t _binary_mx_bench_bin_start[];
#define MXB_AT(off) (_binary_mx_bench_bin_start + (off))
""")
print("blob", len(blob), "bytes")
