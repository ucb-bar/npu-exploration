#!/usr/bin/env python3
"""HDUMP lines of a Spike run of llama_layer_e2e (-DE2E_DUMP_H) -> data/llama_layer_e2e_h_expect.h."""
import sys
from pathlib import Path
b = bytes.fromhex("".join(l.split()[1] for l in open(sys.argv[1]) if l.startswith("HDUMP ")))
assert len(b) == 64 * 5632, len(b)
out = Path(__file__).resolve().parent.parent / "data" / "llama_layer_e2e_h_expect.h"
rows = ",\n".join(", ".join("0x%02x" % x for x in b[i:i + 32]) for i in range(0, len(b), 32))
out.write_text("// GENERATED by gen/dump_h_expect.py from a Spike run: llama_layer_e2e's SwiGLU MX codes h [64][5632].\n"
               "static const uint8_t E2E_H_EXPECT[64 * 5632] = {\n" + rows + "\n};\n")
print("wrote", out, len(b), "bytes")
