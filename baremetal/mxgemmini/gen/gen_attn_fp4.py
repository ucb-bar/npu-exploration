#!/usr/bin/env python3
"""FP4 (E2M1) data for src/attn_flash.c with ATTN_FP4: the same Q/K/V sources as gen_attn_vpu.py, MXFP4 (pmax 0, the
shipped convention) instead of E4M3, packed as the quad mesh reads them, plus the expected O hash from the bit-exact
golden (golden_attn_flash.flash, P through the FP4 SPAD_REQUANT).

  Q4_IN  [SQ/2][D]  row pairs: byte (r, k) = row 2r low nibble | row 2r+1 high      Q_SCALES  [D/32][SQ]
  KT4_IN [D][SK/2]  byte (k, n) = key 2n low nibble | key 2n+1 high                  KT_SCALES [D/32][SK]
  V4_IN  [SK][D/2]  byte (s, n) = dim 2n low | dim 2n+1 high                          V_SCALES  [SK/32][D]

    ../../../.venv/bin/python3 gen_attn_fp4.py --capture ../../../out/layer_capture/attn_qkv_layer5_h{0,1}_s2112.npz \\
        --sq 64 --sk 2048 --bk 128 --tag _llama_2h_fp4
    ../../../.venv/bin/python3 gen_attn_fp4.py --sq 64 --sk 2048 --d 128 --scale-in-q --bk 128 --bk-first 32 --bk-last 96 \\
        --tag _llama7b_fp4
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

import golden_llama_layer_e2e as G
import golden_attn_flash as F

DATA = Path(__file__).resolve().parent.parent / "data"


def rows(a, w):
    return ",\n".join("  { " + ", ".join(f"0x{int(v):0{w}x}" for v in r) + " }" for r in np.atleast_2d(a))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sq", type=int, default=64)
    ap.add_argument("--sk", type=int, default=2048)
    ap.add_argument("--d", type=int, default=64)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--capture", type=Path, nargs="+", default=None)
    ap.add_argument("--scale-in-q", action="store_true")
    ap.add_argument("--bk", type=int, required=True)
    ap.add_argument("--bk-first", type=int, default=None)
    ap.add_argument("--bk-last", type=int, default=None)
    ap.add_argument("--tag", required=True)
    a = ap.parse_args()
    Sq, Sk, d, H = a.sq, a.sk, a.d, 1
    if a.capture:
        zs = [np.load(c) for c in a.capture]
        z, H = zs[0], len(zs)
        T, d = int(z["seq"]), int(z["Q"].shape[1])
        q0 = T - Sq
        Q = np.vstack([o["Q"][q0:q0 + Sq] for o in zs]).astype(np.float32)
        K, V = z["K"][:Sk].astype(np.float32), z["V"][:Sk].astype(np.float32)
        Sq *= H
        src = f"TinyLlama layer {int(z['layer'])} heads {','.join(str(int(o['head'])) for o in zs)}, queries {q0}..{T - 1}"
    else:
        rng = np.random.default_rng(a.seed)
        Q, K, V = (rng.standard_normal((n, d)).astype(np.float32) for n in (Sq, Sk, Sk))
        src = f"random N(0,1), seed {a.seed}"
    if a.scale_in_q:
        Q = (Q / np.sqrt(d)).astype(np.float32)
    qt, qs = G.mxfp4_weights(np.ascontiguousarray(Q.T), 0)      # [D][SQ], [D/32][SQ]
    ktc, kts = G.mxfp4_weights(np.ascontiguousarray(K.T), 0)    # [D][SK], [D/32][SK]
    vc, vs = G.mxfp4_weights(V, 0)                              # [SK][D], [SK/32][D]
    qc = np.ascontiguousarray(qt.T)
    fold = 0 if a.scale_in_q else {16: 2, 64: 3, 256: 4}[d]
    bl = F.blocks(Sk, a.bk, a.bk_first, a.bk_last)
    O, h = F.flash(qc, qs, ktc, kts, vc, vs, bl, fold, None, fp4=True)
    deq = lambda c, s, ax: G.fp4_decode(c).astype(np.float64) * np.repeat(np.exp2(s.astype(np.float64) - 127), 32, axis=ax)
    Qd, Kd, Vd = deq(qc, qs.T, 1), deq(ktc, kts, 0).T, deq(vc, vs, 0)
    S = Qd @ Kd.T * (1.0 if a.scale_in_q else 1 / np.sqrt(d))
    E = np.exp(S - S.max(1, keepdims=True))
    O_ref = (E / E.sum(1, keepdims=True)) @ Vd
    Of = G.bf2f(O).astype(np.float64)
    rel = np.linalg.norm(Of - O_ref) / np.linalg.norm(O_ref)
    print(f"  Sq {Sq} Sk {Sk} d {d}: O hash {h:016x}; rel_fro vs fp64 attention on the FP4 inputs {rel:.3e}")
    pk = lambda x: (x[0::2] | (x[1::2] << 4)).astype(np.uint8)
    hdr, exp = DATA / f"attn_vpu{a.tag}.h", DATA / f"attn_flash{a.tag}_expect.h"
    guard = f"INCLUDE_ATTN_VPU{a.tag.upper()}_H"
    f32 = np.ascontiguousarray(O_ref, dtype=np.float32).view(np.uint32)
    hdr.write_text(f"""// GENERATED by gen/gen_attn_fp4.py -- do not edit. FP4 (MXFP4, pmax 0) attention data for attn_flash.c ATTN_FP4.
// Q/K/V: {src}. Layouts: see the generator.
#ifndef {guard}
#define {guard}
#include <stdint.h>
#define ATTN_SQ {Sq}
#define ATTN_SK {Sk}
#define ATTN_D  {d}
#define ATTN_CAUSAL 0
#define ATTN_HEADS  {H}
#define ATTN_SCALE_IN_Q {int(a.scale_in_q)}
#define ATTN_FP4 1
static const uint8_t Q4_IN[ATTN_SQ / 2][ATTN_D] __attribute__((aligned(64))) = {{
{rows(pk(qc), 2)}
}};
static const uint8_t Q_SCALES[ATTN_D / 32][ATTN_SQ] __attribute__((aligned(64))) = {{
{rows(qs, 2)}
}};
static const uint8_t KT4_IN[ATTN_D][ATTN_SK / 2] __attribute__((aligned(64))) = {{
{rows(pk(ktc.T).T, 2)}
}};
static const uint8_t KT_SCALES[ATTN_D / 32][ATTN_SK] __attribute__((aligned(64))) = {{
{rows(kts, 2)}
}};
static const uint8_t V4_IN[ATTN_SK][ATTN_D / 2] __attribute__((aligned(64))) = {{
{rows(pk(vc.T).T, 2)}
}};
static const uint8_t V_SCALES[ATTN_SK / 32][ATTN_D] __attribute__((aligned(64))) = {{
{rows(vs, 2)}
}};
// fp64 attention on the dequantized FP4 inputs
static const uint32_t O_REF_F_F32[ATTN_SQ][ATTN_D] = {{
{rows(f32, 8)}
}};
#endif
""")
    exp.write_text(f"// golden_attn_flash.flash (fp4, bit-exact rtl_exact mesh + VPU + FP4 SPAD_REQUANT), blocks "
                   f"{bl[0]} + {len(bl) - 2} x {a.bk} + {bl[-1]}.\n#define EXP_FLASH_HASH_O 0x{h:016x}ULL\n")
    print(f"  wrote {hdr}, {exp}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
