#!/usr/bin/env python3
"""Data for src/moe_layer_mx.c: the MoE block of a gpt-oss-20b layer (moe_mx_common.GPTOSS), synthetic weights at the
model's exact shapes.

Two kinds of blob, linked together into each ELF:
  data/moe_experts_<fmt>.{bin,h}   all 32 experts, quantized for the experts' format (fp8: E4M3, fp4: E2M1), one block
                                   per expert at a fixed stride: Wg, Wu [D][F], Wd [F][D] as codes [K][N] (E4M3) or
                                   packed nibbles [K][N/2] (E2M1, low nibble = even column) + E8M0 scales [K/32][N],
                                   then the BF16 biases bg, bu [F], bd [D]. The same experts for every input.
  data/moe_in_<cfg>.{bin,h}        one input (moe_mx_common.CFGS): T tokens h [T][D] BF16, the RMSNorm gain, the router
                                   (E4M3 codes [D][64] + scales [D/32][64], BF16 bias [64]; columns 32.. are padding),
                                   the target routing [T][4] and the fp64 reference (moe output, h_out) for accuracy.

The router is SOLVED for a target routing: the T rows of the normalized input span a T-dim space, so the minimum-norm
W_r = pinv(xn) (L - b_r) gives any target logits L exactly in fp64. L puts the 4 target experts at ~+3 and the rest at
~-2, a margin the E4M3 router's rounding cannot cross, so the device routes as targeted. (Whatever it does, the golden
follows the device's own logits: the routing is never assumed, only aimed.) The targets: token 0 draws 4 of 32
uniformly; each later token keeps each of the previous token's experts with probability rho, fresh draws for the rest.

    ../../../.venv/bin/python3 gen_moe_mx.py --experts fp8 fp4          # the expert blobs (~0.8 / 0.4 GB)
    ../../../.venv/bin/python3 gen_moe_mx.py --cfg all                  # every input
"""
from __future__ import annotations

import argparse
import sys
import time

import numpy as np

import moe_mx_common as C
import golden_llama_layer_e2e as GL
from gen_llama_layer_mx import Blob, mx_e4m3, pk_cols, quant_weight

M_ = C.GPTOSS


def expert_weights(e: int) -> dict:
    """Expert e's fp32 weights and BF16-exact biases (fp64), seeded per expert."""
    rng = np.random.default_rng(20250805 + 7919 * e)
    D, F = M_.D, M_.F
    W = {"g": rng.standard_normal((D, F), dtype=np.float32) / np.float32(np.sqrt(D)),
         "u": rng.standard_normal((D, F), dtype=np.float32) / np.float32(np.sqrt(D)),
         "d": rng.standard_normal((F, D), dtype=np.float32) / np.float32(np.sqrt(F))}
    B = {"g": rng.standard_normal(F) * 0.1, "u": rng.standard_normal(F) * 0.1, "d": rng.standard_normal(D) * 0.02}
    B = {k: GL.bf2f(GL.d2bf(v)).astype(np.float64) for k, v in B.items()}
    return {"W": W, "B": B}


def act(g, u):
    """gpt-oss's gated activation (fp64)."""
    g = np.minimum(g, M_.limit)
    u = np.clip(u, -M_.limit, M_.limit)
    return g / (1 + np.exp(-M_.alpha * g)) * (u + 1)


# ---------------------------------------------------------------- the experts
def quant_expert(W, fmt):
    """fp32 W [K][N] -> {suffix: (array, dtype)}: E4M3 as llama_mx; E2M1 with block scales at W_PMAX_FP4."""
    if fmt == "fp8":
        return quant_weight(W, fmt)
    c, s = GL.mxfp4_weights(W, C.W_PMAX_FP4)
    return {"C": (pk_cols(c), np.uint8), "S": (s, np.uint8)}


def gen_experts(fmt: str) -> None:
    t0 = time.time()
    D, F = M_.D, M_.F
    name = C.experts_name(fmt)
    path = C.DATA / f"{name}.bin"
    stride, layout = None, None
    with open(path, "wb") as f:
        for e in range(M_.E):
            X = expert_weights(e)
            b = Blob()
            for k in "gud":
                for suf, (arr, dt) in quant_expert(X["W"][k], fmt).items():
                    b.add(f"{k.upper()}{suf}", arr, dt)
            for k in "gud":
                b.add(f"B{k.upper()}", GL.d2bf(X["B"][k]), np.uint16)
            b.buf.extend(b"\0" * ((-len(b.buf)) % 4096))   # experts on 4 KB boundaries
            if stride is None:
                stride, layout = len(b.buf), b.desc
            assert len(b.buf) == stride
            f.write(bytes(b.buf))
            print(f"[experts {fmt}] expert {e} ({time.time() - t0:.0f}s)", flush=True)
    offs = "\n".join(f"#define MOE_XO_{n:<4s} {o}u   // {sh}" for n, o, _, sh in layout)
    (C.DATA / f"{name}.h").write_text(f"""// GENERATED by gen/gen_moe_mx.py -- do not edit.
// The {M_.E} experts of a {M_.name} MoE layer (synthetic weights at its shapes), {fmt}: expert e at e * MOE_X_STRIDE.
// Wg / Wu [{D}][{F}], Wd [{F}][{D}] ({'E4M3 codes [K][N]' if fmt == 'fp8' else 'E2M1 nibbles [K][N/2]'}, E8M0 scales [K/32][N]); BF16 biases.
#ifndef INCLUDE_MOE_EXPERTS_H
#define INCLUDE_MOE_EXPERTS_H
#include <stdint.h>
#define MOE_FMT      {C.FORMATS[fmt]}      // experts: 0 E4M3, 2 FP4 E2M1 (the router is always E4M3)
#define MOE_FMT_NAME "{fmt}"
#define MOE_X_STRIDE {stride}u
#define MOE_W_PMAX   {C.W_PMAX_FP4 if fmt == "fp4" else 0}      // E2M1 weight block scale 2^(floor(log2 amax) - this)
extern const uint8_t _binary_{name}_bin_start[];
#define MOE_X(e, n, type) ((const type *) (_binary_{name}_bin_start + (size_t) (e) * MOE_X_STRIDE + MOE_XO_##n))
{offs}
#endif
""")
    print(f"[experts {fmt}] wrote {name}.bin ({M_.E * stride / 1e6:.0f} MB, {time.time() - t0:.0f}s)", flush=True)


# ---------------------------------------------------------------- one input
def rms(x, w, eps):
    return x / np.sqrt((x * x).mean(axis=1, keepdims=True) + eps) * w


def target_routing(T: int, rho: float, rng) -> np.ndarray:
    sel = np.zeros((T, M_.K), np.int64)
    sel[0] = rng.choice(M_.E, M_.K, replace=False)
    for t in range(1, T):
        keep = [e for e in sel[t - 1] if rng.random() < rho]
        rest = rng.choice([e for e in range(M_.E) if e not in keep], M_.K - len(keep), replace=False)
        sel[t] = np.array(keep + list(rest))
    return sel


def gen_cfg(key: str) -> None:
    t0 = time.time()
    cfg = C.CFGS[key]
    T, D, E = cfg.T, M_.D, M_.E
    rng = np.random.default_rng(sum(map(ord, key)) * 104729)
    hs = rng.standard_normal((T, D))
    hs[:, rng.choice(D, 4, replace=False)] *= 20.0   # a few loud channels, as the llama_mx inputs
    h_bits = GL.d2bf(hs)
    h = GL.bf2f(h_bits).astype(np.float64)
    ln = GL.bf2f(GL.d2bf(np.abs(1 + 0.2 * rng.standard_normal(D)))).astype(np.float64)
    xn = rms(h, ln, M_.eps)
    sel = target_routing(T, cfg.rho, rng)
    L = -2.0 + 0.3 * rng.standard_normal((T, E))
    for t in range(T):
        L[t, sel[t]] = 3.0 + 0.5 * rng.standard_normal(M_.K)
    br = GL.bf2f(GL.d2bf(0.1 * rng.standard_normal(E))).astype(np.float64)
    Wr = np.linalg.pinv(xn) @ (L - br)                      # [D][E]: xn @ Wr + br = L
    Wr64 = np.zeros((D, C.ROUTER_N), np.float32); Wr64[:, :E] = Wr
    br64 = np.zeros(C.ROUTER_N); br64[:E] = br

    # fp64 reference: routing from the fp64 logits, softmax over the picked 4, the experts on the unquantized weights
    logits = xn @ Wr + br
    moe = np.zeros((T, D))
    for t in range(T):
        top = np.argsort(-logits[t], kind="stable")[:M_.K]
        p = np.exp(logits[t, top] - logits[t, top].max()); p /= p.sum()
        for k, e in enumerate(top):
            X = _expert_cache(e)
            g = xn[t] @ X["W"]["g"] + X["B"]["g"]
            u = xn[t] @ X["W"]["u"] + X["B"]["u"]
            moe[t] += p[k] * (act(g, u) @ X["W"]["d"] + X["B"]["d"])
        assert set(top) == set(sel[t]), f"fp64 routing missed the target at token {t}"
    hout = h + moe

    b = Blob()
    b.add("H", h_bits, np.uint16)
    b.add("W_LN", GL.d2bf(ln), np.uint16)
    c, s = mx_e4m3(Wr64, 0)
    b.add("WR_C", c, np.uint8)
    b.add("WR_S", s, np.uint8)
    b.add("BR", GL.d2bf(br64), np.uint16)
    b.add("TARGET", sel.astype(np.uint8), np.uint8)
    b.add("REF_MOE", moe.astype(np.float32), np.float32)
    b.add("REF_HOUT", hout.astype(np.float32), np.float32)
    name = C.cfg_name(key)
    (C.DATA / f"{name}.bin").write_bytes(bytes(b.buf))
    offs = "\n".join(f"#define MOE_OFF_{n:<9s} {o}u" for n, o in b.off.items())
    table = "\n".join(f"//   {n:<9s} @ {o:>9d}  {sz:>9d} B  {sh}" for n, o, sz, sh in b.desc)
    distinct = len(set(sel.reshape(-1).tolist()))
    (C.DATA / f"{name}.h").write_text(f"""// GENERATED by gen/gen_moe_mx.py -- do not edit.
// One input of the {M_.name} MoE block for src/moe_layer_mx.c: {T} tokens, target routing locality {cfg.rho}
// ({distinct} distinct experts targeted). Data in {name}.bin, linked as a binary section.
{table}
#ifndef INCLUDE_MOE_IN_H
#define INCLUDE_MOE_IN_H
#include <stdint.h>
#define MOE_CFG_NAME "{key}"
#define MOE_T     {T}
#define MOE_D     {D}
#define MOE_F     {M_.F}
#define MOE_E     {E}
#define MOE_K     {M_.K}
#define MOE_RN    {C.ROUTER_N}
#define MOE_EPS   {M_.eps:.10g}f
#define MOE_ALPHA {M_.alpha:.10g}f
#define MOE_LIMIT {M_.limit:.10g}f
#define MOE_TARGET_DISTINCT {distinct}
extern const uint8_t _binary_{name}_bin_start[];
#define MOE_AT(off, type) ((const type *) (_binary_{name}_bin_start + (off)))
{offs}
#endif
""")
    print(f"[{key}] wrote {name}.bin ({len(b.buf) / 1e6:.1f} MB, {distinct} distinct experts targeted, "
          f"{time.time() - t0:.0f}s)", flush=True)


_XC: dict = {}


def _expert_cache(e: int) -> dict:
    if e not in _XC:
        _XC[e] = expert_weights(e)
        _XC[e]["W"] = {k: v.astype(np.float64) for k, v in _XC[e]["W"].items()}
    return _XC[e]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--experts", nargs="*", default=[], choices=list(C.FORMATS))
    ap.add_argument("--cfg", nargs="*", default=[])
    a = ap.parse_args()
    for f in a.experts:
        gen_experts(f)
    for k in (list(C.CFGS) if a.cfg == ["all"] else a.cfg):
        gen_cfg(k)
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(C.NPU))
    raise SystemExit(main())
