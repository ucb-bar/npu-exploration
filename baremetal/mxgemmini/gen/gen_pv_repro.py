#!/usr/bin/env python3
"""Turn a `llama_attention_full_dgb -DDGB_DUMP_PV_HEAD=h` spike log into a ladder header.

WHY. On the FPGA, llama_attention_full is bit-exact everywhere except ONE element: head 31's
`O = P @ V` comes out 0xbc18 at (row 31, col 13) where the model says 0xbc17, and the requantizer
then (correctly) turns that one-ulp difference into a different FP8 code. The dump is that tile
exactly as the device is given it, so the rung this writes re-runs the one matmul on its own --
small enough (32x32x64) for RTL simulation and a waveform.

The golden is spike's own BF16 output, and it is cross-checked here against mxq's MXGEMMINI
(`mxq.matmul.systolic`) before anything is written: the rung must PASS on spike, and a
disagreement between spike and the model would make the RTL comparison meaningless.

    # 1. dump on spike (see src/llama_attention_full_dgb.c)
    make OUT=<dir> EXTRA_llama_attention_full_dgb=-DDGB_DUMP_PV_HEAD=31 <dir>/spike/llama_attention_full_dgb
    spike --extlib=... --extension=gemmini <dir>/spike/llama_attention_full_dgb > pv31.log
    # 2. header
    cd gen && ../../../.venv/bin/python3 gen_pv_repro.py pv31.log            # -> data/mx_ladder_mxl20.h
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
NPU = HERE.parents[2]
DATA = HERE.parent / "data"
ROCC = NPU.parent / "software" / "gemmini-rocc-tests"
sys.path.insert(0, str(NPU))
sys.path.insert(0, str(ROCC))
sys.path.insert(0, str(HERE))

BLOCK = 32


def parse(log: Path) -> dict:
    """The `dump-begin ... dump-end` block: header fields plus one flat array per `dump` line."""
    lines = log.read_text(errors="replace").splitlines()
    try:
        i = next(k for k, l in enumerate(lines) if l.startswith("dump-begin"))
    except StopIteration:
        raise SystemExit(f"{log}: no dump-begin line -- was the ELF built with -DDGB_DUMP_PV_HEAD?")
    f = lines[i].split()[1:]
    out: dict = {k: int(v) for k, v in zip(f[::2], f[1::2])}
    k = i + 1
    while not lines[k].startswith("dump-end"):
        _, name, n, nbytes = lines[k].split()
        n, nbytes = int(n), int(nbytes)
        vals: list[int] = []
        k += 1
        while len(vals) < n:
            vals += [int(t, 16) for t in lines[k].split()]
            k += 1
        if len(vals) != n:
            raise SystemExit(f"{name}: expected {n} values, got {len(vals)}")
        out[name] = np.array(vals, dtype=np.uint8 if nbytes == 1 else np.uint16)
    return out


def rows(a: np.ndarray, width: int) -> str:
    fmt = f"0x%0{width}x"
    return ",\n".join("  {" + ", ".join(fmt % v for v in r) + "}" for r in a)


def model_check(d: dict) -> None:
    """spike's BF16 must equal mxq's MXGEMMINI, or the rung grades against nothing in particular."""
    import torch
    import gen_llama_attn_full as GA
    import gen_matmul_llama as G
    from mxq import matmul, schedule
    M, K, N = d["M"], d["K"], d["N"]
    PA = torch.tensor(GA._p_from(d["A_CODES"].reshape(M, K))).t()                 # K x M
    PB = torch.tensor(GA._p_from(d["B_CODES"].reshape(K, N)))                     # K x N
    XA = torch.pow(2.0, torch.tensor(d["A_SCALES"].reshape(K // BLOCK, M).astype(np.float32)) - 127)
    XB = torch.pow(2.0, torch.tensor(d["B_SCALES"].reshape(K // BLOCK, N).astype(np.float32)) - 127)
    C = G.bf16_bits(matmul.systolic(PA, XA, PB, XB, matmul.MXGEMMINI(), schedule.HW_FINAL).numpy())
    diff = int(np.count_nonzero(C != d["C_BF16"].reshape(M, N)))
    if diff:
        raise SystemExit(f"spike and mxq disagree on {diff}/{M * N} elements -- not writing")
    print(f"  spike BF16 == mxq MXGEMMINI on all {M * N} elements")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("log", type=Path, help="spike log of the -DDGB_DUMP_PV_HEAD build")
    ap.add_argument("--name", default="mxl20")
    ap.add_argument("--no-model-check", action="store_true")
    a = ap.parse_args()

    d = parse(a.log)
    M, K, N, h, kv = d["M"], d["K"], d["N"], d["head"], d["kv"]
    if not a.no_model_check:
        model_check(d)
    GK = K // BLOCK
    why = (f"llama_attention_full head {h}'s P @ V tile, EXACTLY as the device is given it -- the one "
           f"matmul the FPGA gets 1 ulp wrong (0xbc18 vs 0xbc17 at row 31 col 13)")
    guard = f"INCLUDE_MX_LADDER_{a.name.upper()}_H"
    hdr = f"""// GENERATED by gen/gen_pv_repro.py from a spike dump -- do not edit. Rung {a.name}.
//
// {why}.
// A = P codes (head {h}), B = V codes (kv head {kv}); golden = spike's BF16, checked equal to
// mxq MXGEMMINI. Source log: {a.log.name}
#ifndef {guard}
#define {guard}

#define LAD_NAME "{a.name}"
#define LAD_WHY  "head {h} P@V from llama_attention_full, verbatim (FPGA: 1 ulp off at row 31 col 13)"

#define LAD_M {M}
#define LAD_K {K}
#define LAD_N {N}
#define LAD_GK {GK}

static const uint8_t LAD_A[{M}][{K}] = {{
{rows(d["A_CODES"].reshape(M, K), 2)}
}};

static const uint8_t LAD_B[{K}][{N}] = {{
{rows(d["B_CODES"].reshape(K, N), 2)}
}};

static const uint8_t LAD_A_SCALES[{GK}][{M}] = {{
{rows(d["A_SCALES"].reshape(GK, M), 2)}
}};

static const uint8_t LAD_B_SCALES[{GK}][{N}] = {{
{rows(d["B_SCALES"].reshape(GK, N), 2)}
}};

static const uint16_t LAD_C_BF16[{M}][{N}] = {{
{rows(d["C_BF16"].reshape(M, N), 4)}
}};

#endif  // {guard}
"""
    out = DATA / f"mx_ladder_{a.name}.h"
    out.write_text(hdr)
    print(f"  {a.name}  M={M} K={K} N={N}  ->  {out.name} ({len(hdr) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
